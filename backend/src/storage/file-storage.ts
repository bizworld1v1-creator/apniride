import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Injectable } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import type { Env } from '../config/env.js';

/**
 * Private file storage for driver documents (CNIC, licence…). Files are never served publicly:
 * only the admin API reads them back.
 * Swap the implementation for S3-compatible storage (e.g. Cloudflare R2) when we run more than one server.
 */
export abstract class FileStorage {
  abstract put(key: string, data: Buffer): Promise<void>;
  /** null if the file doesn't exist. */
  abstract get(key: string): Promise<Buffer | null>;
  /** Succeeds if the file is already gone. */
  abstract delete(key: string): Promise<void>;
}

/** Local disk under UPLOAD_DIR. Fine for development and a single server. */
@Injectable()
export class LocalFileStorage extends FileStorage {
  private readonly root: string;

  constructor(config: ConfigService<Env, true>) {
    super();
    this.root = path.resolve(config.get('UPLOAD_DIR', { infer: true }));
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
  }

  async get(key: string): Promise<Buffer | null> {
    try {
      return await readFile(this.resolve(key));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }

  /** Keys are generated by us, but never let one escape the upload folder anyway. */
  private resolve(key: string): string {
    const file = path.resolve(this.root, key);
    if (!file.startsWith(this.root + path.sep)) throw new Error(`Invalid storage key: ${key}`);
    return file;
  }
}
